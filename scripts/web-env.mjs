// Writes frontend/web/.env.local with the address and publishable key of the shared local
// Supabase instance "sarmata" (plan 2). Run after `pnpm db:start`. When the root .env.ai.local
// exists (plan 5), the AI settings of the app are copied from it too.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const status = JSON.parse(
  execFileSync('pnpm', ['exec', 'supabase', 'status', '-o', 'json'], {
    cwd: `${root}/database`,
    encoding: 'utf8',
  }),
);
const key = status.PUBLISHABLE_KEY ?? status.ANON_KEY;

if (!status.API_URL || !key) {
  throw new Error(
    'supabase status returned no API_URL or key. Is the stack running (pnpm db:start)?',
  );
}

const lines = [
  '# Generated by `pnpm web:env` from `supabase status`. Not committed.',
  `SUPABASE_URL=${status.API_URL}`,
  `SUPABASE_PUBLISHABLE_KEY=${key}`,
];

const aiKeys = ['AI_BASE_URL', 'AI_MODEL', 'AI_DECISION_URL'];
const aiEnvFile = `${root}/.env.ai.local`;
if (existsSync(aiEnvFile)) {
  for (const line of readFileSync(aiEnvFile, 'utf8').split('\n')) {
    const name = line.split('=')[0]?.trim();
    if (name && aiKeys.includes(name)) lines.push(line.trim());
  }
}

writeFileSync(`${root}/frontend/web/.env.local`, [...lines, ''].join('\n'));
console.log('Wrote frontend/web/.env.local');
