// Writes frontend/web/.env.local with the address and publishable key of the shared local
// Supabase instance "sarmata". Run after `pnpm db:start`. A SUPABASE_URL already set in the shell
// (an external instance) wins, as in with-supabase-env.mjs, and needs SUPABASE_PUBLISHABLE_KEY too.
// When the root .env.ai.local exists (written by `pnpm ai:env`), the AI settings of the app are
// copied from it too.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { localSupabaseEnv } from './supabase-env.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));

function supabaseSettings() {
  const { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } = process.env;
  if (!SUPABASE_URL) return localSupabaseEnv();
  if (!SUPABASE_PUBLISHABLE_KEY) {
    throw new Error(
      'SUPABASE_URL is set but SUPABASE_PUBLISHABLE_KEY is not. Set both or neither.',
    );
  }
  return { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY };
}

const { SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY } = supabaseSettings();

const lines = [
  `# Generated by \`pnpm web:env\` from ${process.env.SUPABASE_URL ? 'the shell environment' : '`supabase status`'}. Not committed.`,
  `SUPABASE_URL=${SUPABASE_URL}`,
  `SUPABASE_PUBLISHABLE_KEY=${SUPABASE_PUBLISHABLE_KEY}`,
];

// Every SARMATA_AI_* setting of @sarmata/ai (backend/ai/src/config.ts) written by pnpm ai:env.
const aiEnvFile = `${root}/.env.ai.local`;
if (existsSync(aiEnvFile)) {
  for (const line of readFileSync(aiEnvFile, 'utf8').split('\n')) {
    const name = line.split('=')[0]?.trim();
    if (name?.startsWith('SARMATA_AI_')) lines.push(line.trim());
  }
}

writeFileSync(`${root}/frontend/web/.env.local`, [...lines, ''].join('\n'));
console.log('Wrote frontend/web/.env.local');
