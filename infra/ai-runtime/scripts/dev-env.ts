import { readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  defaultDataDir,
  type BielikOneEngine,
  type BielikOnePackageId,
  type Machine,
  type ProgressEvent,
} from '../src/index.ts';

/** One llama-server for every worktree, next to the local Supabase ports 55421 and 55422 (database/supabase/config.toml). */
export const DEV_PORT = 55490;

const REPO_ROOT = fileURLToPath(new URL('../../../', import.meta.url));

export function devDataDir(machine: Machine): string {
  return defaultDataDir(machine.os, process.env, homedir());
}

export const devStateFile = (dataDir: string): string => join(dataDir, 'dev-llama-server.json');
export const devBielikOneStateFile = (dataDir: string): string =>
  join(dataDir, 'dev-bielik-one.json');
const bielikOneConfigFile = (dataDir: string): string => join(dataDir, 'bielik-one.json');

/** Bielik-One as pnpm ai:setup --with-bielik-one installed it, shared by all worktrees. */
export interface DevBielikOneConfig {
  engine: BielikOneEngine;
  packageId: BielikOnePackageId;
  executable: string;
  /** Frontend URL without /v1. */
  url: string;
  /** Fits next to the text model. False: run one at a time (pnpm ai:start --only). */
  together: boolean;
}

/** A detached Bielik-One started by pnpm ai:start. */
export interface DevBielikOneState {
  pids: number[];
  url: string;
}

export async function readJsonOrNull<T>(path: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(path, 'utf8')) as T;
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
    throw error;
  }
}

export const readBielikOneConfig = (dataDir: string): Promise<DevBielikOneConfig | null> =>
  readJsonOrNull<DevBielikOneConfig>(bielikOneConfigFile(dataDir));

export async function writeBielikOneConfig(
  dataDir: string,
  config: DevBielikOneConfig,
): Promise<void> {
  await writeFile(bielikOneConfigFile(dataDir), `${JSON.stringify(config, null, 2)}\n`);
}

export const isAlive = (pid: number): boolean => {
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
};

/** Endpoints the app reads to reach the local AI runtime. Either may be missing. */
export interface AiEnv {
  text?: { baseUrl: string; model: string };
  /** Bielik-One frontend base URL with /v1. */
  decision?: { baseUrl: string };
}

/**
 * Writes the generated .env.ai.local in the repo root (ignored by git through `.env*.local`).
 * .env.local belongs to SOPS and is never touched here. direnv loads both files (.envrc).
 */
export async function writeAiEnv(env: AiEnv): Promise<string> {
  const path = join(REPO_ROOT, '.env.ai.local');
  await writeFile(path, `${aiEnvLines(env).join('\n')}\n`);
  return path;
}

/**
 * Limits of one model call: short tasks 2 minutes, long ones (sheet draft, conversation preparation,
 * HR signals) 10 minutes, and 5 minutes for the cold start of semble. Same values as the defaults of
 * backend/ai/src/config.ts, written out so they are easy to find and change.
 */
export const AI_TIMEOUTS = {
  SARMATA_AI_TIMEOUT_MS: 120_000,
  SARMATA_AI_LONG_TIMEOUT_MS: 600_000,
  SARMATA_SEMBLE_TIMEOUT_MS: 300_000,
} as const;

/** The lines of .env.ai.local. */
export function aiEnvLines(env: AiEnv): string[] {
  return [
    '# Generated by pnpm ai:setup, ai:env and ai:start (infra/ai-runtime). Do not edit, do not commit.',
    // Names follow the contract of @sarmata/ai (backend/ai/src/config.ts).
    `SARMATA_AI_ENABLED=${env.text || env.decision ? 'true' : 'false'}`,
    ...Object.entries(AI_TIMEOUTS).map(([name, value]) => `${name}=${String(value)}`),
    ...(env.text
      ? [`SARMATA_AI_TEXT_BASE_URL=${env.text.baseUrl}`, `SARMATA_AI_TEXT_MODEL=${env.text.model}`]
      : []),
    // Without Bielik-One the text model decides with forced JSON (ADR 0005).
    ...(env.decision
      ? [
          `SARMATA_AI_DECISION_BASE_URL=${env.decision.baseUrl}`,
          'SARMATA_AI_DECISION_MODEL=decision',
        ]
      : []),
  ];
}

export const describeError = (error: unknown): string =>
  error instanceof Error ? error.message : String(error);

export function printProgress(event: ProgressEvent): void {
  if (event.kind === 'step') {
    console.log(event.message);
    return;
  }
  const percent = Math.floor((event.receivedBytes / event.totalBytes) * 100);
  process.stdout.write(`\r  ${event.file}: ${percent}%`);
  if (event.receivedBytes === event.totalBytes) process.stdout.write('\n');
}
